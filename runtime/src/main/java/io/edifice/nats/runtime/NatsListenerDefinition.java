package io.edifice.nats.runtime;

import jakarta.enterprise.invoke.Invoker;

/**
 * A {@code @BrokerListener} method found at build time.
 *
 * @param subject     the subject listened to
 * @param description what the endpoint does
 * @param target      the bean method, as {@code Class#method}, for logs
 * @param requestType the type of the single parameter
 * @param replies     whether the method returns a value to send back, {@code false} for {@code void}
 * @param broadcast   whether every instance receives the messages: subscribed without queue group
 * @param invoker     the invoker generated by ArC, which looks the bean up
 */
public record NatsListenerDefinition(SubjectTemplate subject, String description, String target, Class<?> requestType,
                                     boolean replies, boolean broadcast,
                                     Invoker<Object, Object> invoker) {
}

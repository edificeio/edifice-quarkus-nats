package io.edifice.nats.runtime;

import io.quarkus.arc.Arc;
import io.quarkus.runtime.RuntimeValue;
import io.quarkus.runtime.annotations.Recorder;
import jakarta.enterprise.invoke.Invoker;

/**
 * Registers the {@code @BrokerListener} methods found at build time, at runtime init.
 */
@Recorder
public class NatsRecorder {

  /**
   * Registers one listener.
   *
   * @param subject     the subject declared
   * @param description what the endpoint does
   * @param target      the bean method, for logs
   * @param requestType the type of the request
   * @param replies     whether the method returns a value
   * @param broadcast   whether every instance receives the messages, without queue group
   * @param invoker     the invoker generated by ArC
   */
  public void addListener(String subject, String description, String target, Class<?> requestType, boolean replies,
                          boolean broadcast, RuntimeValue<Invoker<Object, Object>> invoker) {
    dispatcher().add(new NatsListenerDefinition(SubjectTemplate.parse(subject), description, target, requestType,
      replies, broadcast, invoker.getValue()));
  }

  /**
   * Subscribes the listeners once NATS is connected, without waiting for it.
   */
  public void startListeners() {
    dispatcher().start();
  }

  private static NatsListenerDispatcher dispatcher() {
    return Arc.container().instance(NatsListenerDispatcher.class).get();
  }
}
